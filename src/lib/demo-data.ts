export function getFleetSummary() {
  const scores = DEMO_DC_HEALTH.map((d) => d.score);
  const avg = scores.reduce((a, b) => a + b, 0) / scores.length;
  const anomalies = DEMO_DC_HEALTH.flatMap((d) => d.anomalies);
  return {
    dcCount: DEMO_DC_HEALTH.length,
    avgScore: Math.round(avg),
    criticalDcs: DEMO_DC_HEALTH.filter((d) => d.level === "critical").length,
    degradedDcs: DEMO_DC_HEALTH.filter((d) => d.level === "degraded").length,
    openAnomalies: anomalies.length,
    highDrift: DEMO_DRIFT.filter((d) => d.severity === "high").length,
    certRisk: DEMO_CERTIFICATES.filter((c) => c.riskScore >= 70).length,
    pendingPlaybooks: DEMO_PLAYBOOK_RUNS.filter((r) =>
      ["pending", "approved"].includes(r.status)
    ).length,
  };
}

export function jitterHealth(metrics: DcHealthMetric[]): DcHealthMetric[] {
  return metrics.map((m) => {
    const jitter = () => (Math.random() - 0.5) * 4;
    const ldap = Math.max(3, m.ldapLatencyMs + jitter());
    const kerberos = Math.max(3, m.kerberosLatencyMs + jitter());
    const lag = Math.max(0, m.replicationLagSeconds + jitter() * 5);
    return {
      ...m,
      ldapLatencyMs: Math.round(ldap),
      kerberosLatencyMs: Math.round(kerberos),
      replicationLagSeconds: Math.round(lag),
      lastSeen: now(),
    };
  });
}

